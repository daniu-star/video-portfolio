    ck('FAST beacon rendered',page.locator('#fastPulse').is_visible())
    ck('bridge drive hidden in FAST mode',not page.locator('#driveQuickStart').is_visible())
    page.screenshot(path=str(ROOT/'qa/screenshots/V7_P4_FAST_portal_desktop.png'),full_page=True)
    page.locator('#fastQuickStart').click();page.wait_for_timeout(160)
    ck('intro appears',page.locator('#fastGameShell').is_visible() and '微弱信号' in page.locator('#fastGameMain').inner_text())
    ck('source attribution visible',page.locator('.fast-game-source a').count()==2)
    ck('real fact simulated data disclaimer', '教学示意' in page.locator('#fastGameMain').inner_text())
    page.screenshot(path=str(ROOT/'qa/screenshots/V7_P4_FAST_intro_desktop.png'),full_page=True)
    page.locator('[data-action="begin"]').click()
    ck('chapter 1 ready',page.evaluate('SpatialApp.FastGame.stage===0'))
    ck('3 emitters active',page.locator('button.fast-device.is-on').count()==3)
    page.locator('[data-action="verify-quiet"]').click()
    ck('missing source feedback', '还有 3 项' in page.locator('#fastGameHint').inner_text())
    for key in ['phone','drone','station']:
      page.locator(f'[data-action="toggle"][data-id="{key}"]').click()
    ck('all toggled off',page.locator('button.fast-device.is-on').count()==0)
    page.locator('[data-action="verify-quiet"]').click()
    ck('chapter 2 ready',page.evaluate('SpatialApp.FastGame.stage===1'))
    ck('first rule core 3km', '3km 案例' in page.locator('#fastGameMain').inner_text())
    page.locator('[data-action="pick"][data-choice="0"]').click()
    ck('wrong choice explained', '不够严谨' in page.locator('.fast-feedback').inner_text())
    page.locator('[data-action="retry-case"]').click()
    for i in range(3):
      page.locator('[data-action="pick"][data-choice="1"]').click()
