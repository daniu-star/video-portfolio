"""V7 P4 full real-browser interaction smoke tests. FAST science content is synthetic; no live SDK credentials used."""
from pathlib import Path
import json,re
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
html=(ROOT/'index.html').read_text(encoding='utf-8')
html=re.sub(r'<link rel="stylesheet" href="([^"]+)">',lambda m:'<style>'+ (ROOT/m[1]).read_text(encoding='utf-8')+'</style>',html)
html=re.sub(r'<script src="([^"]+)"></script>',lambda m:'<script>'+ (ROOT/m[1]).read_text(encoding='utf-8').replace('</script>','<\\/script>')+'</script>',html)
report={'phase':'V7-P4','method':'Chromium inline bundled JS/CSS under about:blank because local host navigation blocked by execution environment; no SDK auth','checks':[],'errors':[]}
def ck(name,good):
    report['checks'].append({'name':name,'passed':bool(good)})
    print(('PASS' if good else 'FAIL')+' | '+name,flush=True)
    if not good:raise AssertionError(name)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-gpu','--disable-dev-shm-usage'])
    context=browser.new_context(viewport={'width':1440,'height':900},device_scale_factor=1)
    page=context.new_page();page.set_default_timeout(6500); errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(html,wait_until='domcontentloaded');page.wait_for_timeout(350)
    ck('HTML and code loaded',page.locator('#fastGameShell').count()==1)
    ck('FAST module initialized',page.evaluate('Boolean(SpatialApp.FastGame.portalTimer)'))
    page.locator('#enterMapBtn').click();page.wait_for_timeout(1340)
    page.locator('#siteSelect').select_option('fast');page.wait_for_timeout(450)
